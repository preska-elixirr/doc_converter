const dictionaries: Record<Language, Record<Key, string>> = { en, hr };

/** Index of the plural form for `count` in `language`. */
export function pluralIndex(language: Language, count: number): number {
  if (language === 'hr') {
    const ones = count % 10;
    const tens = count % 100;
    if (ones === 1 && tens !== 11) return 0;
    if (ones >= 2 && ones <= 4 && (tens < 12 || tens > 14)) return 1;
    return 2;
  }
  return count === 1 ? 0 : 1;
}

function fill(template: string, vars?: Record<string, string | number>): string {
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (match, name: string) => (name in vars ? String(vars[name]) : match));
}

/** A translated string with `{name}` placeholders filled in. */
export function translate(language: Language, key: Key, vars?: Record<string, string | number>): string {
  const template = dictionaries[language][key] ?? en[key] ?? key;
  return fill(template, vars);
}

/** The plural form of `key` for `count`; `{count}` is filled in automatically. */
export function translatePlural(language: Language, key: Key, count: number, vars?: Record<string, string | number>): string {
  const forms = (dictionaries[language][key] ?? en[key]).split('|');
  const form = forms[Math.min(pluralIndex(language, count), forms.length - 1)];
  return fill(form, { count, ...vars });
}

/** Backend status details that the UI knows how to translate. Others stay as sent. */
const BACKEND_DETAILS: Record<string, Key> = {
  'Queued': 'status.queued',
  'Working…': 'status.working',
  'Saved': 'status.saved',
  'Saved; PDF/A validation passed.': 'standards.saved',
  'Saved; PDF/UA machine checks passed. Human review required.': 'standards.saved_ua',
  'PDF validation failed. No output was saved.': 'standards.not_saved',
  'Converting to PDF…': 'status.converting',
  'Ready to merge': 'status.ready_to_merge',
  'Combined': 'status.combined',
  'Cancelled. No output was saved.': 'status.cancelled',
};

export function translateDetail(language: Language, detail: string): string {
  const key = BACKEND_DETAILS[detail];
  return key ? translate(language, key) : detail;
}

/** Picks the language the browser reports, defaulting to English. */
export function detectLanguage(): Language {
  const tag = (typeof navigator !== 'undefined' ? navigator.language : '') || '';
  return tag.toLowerCase().startsWith('hr') ? 'hr' : 'en';
}
